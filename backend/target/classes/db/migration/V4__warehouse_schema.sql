-- V4: Warehouse schema
CREATE TABLE warehouses (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    warehouse_code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    address VARCHAR(500),
    city VARCHAR(100),
    state VARCHAR(100),
    pincode VARCHAR(10),
    latitude DECIMAL(10,8),
    longitude DECIMAL(11,8),
    capacity_mt DECIMAL(12,3),
    manager_id BIGINT,
    status ENUM('ACTIVE','INACTIVE','MAINTENANCE') NOT NULL DEFAULT 'ACTIVE',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_by VARCHAR(50) DEFAULT 'system',
    updated_by VARCHAR(50),
    FOREIGN KEY (manager_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE warehouse_locations (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    warehouse_id BIGINT NOT NULL,
    location_code VARCHAR(30) NOT NULL,
    name VARCHAR(100),
    zone VARCHAR(50),
    capacity_mt DECIMAL(10,3),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_by VARCHAR(50) DEFAULT 'system',
    updated_by VARCHAR(50),
    FOREIGN KEY (warehouse_id) REFERENCES warehouses(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE gate_entries (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    entry_number VARCHAR(30) NOT NULL UNIQUE,
    warehouse_id BIGINT NOT NULL,
    trip_id BIGINT,
    vehicle_id BIGINT,
    driver_name VARCHAR(100),
    driver_phone VARCHAR(20),
    purpose ENUM('INBOUND','OUTBOUND','TRANSFER','OTHER') NOT NULL,
    reference_type VARCHAR(50),
    reference_id BIGINT,
    entry_time DATETIME NOT NULL,
    exit_time DATETIME,
    status ENUM('ENTERED','IN_PROGRESS','COMPLETED','CANCELLED') NOT NULL DEFAULT 'ENTERED',
    notes VARCHAR(500),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_by VARCHAR(50) DEFAULT 'system',
    updated_by VARCHAR(50),
    FOREIGN KEY (warehouse_id) REFERENCES warehouses(id),
    FOREIGN KEY (trip_id) REFERENCES trips(id),
    FOREIGN KEY (vehicle_id) REFERENCES vehicles(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE weighments (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    weighment_number VARCHAR(30) NOT NULL UNIQUE,
    gate_entry_id BIGINT,
    warehouse_id BIGINT NOT NULL,
    vehicle_id BIGINT,
    trip_id BIGINT,
    purchase_order_id BIGINT,
    gross_weight DECIMAL(12,3) NOT NULL,
    tare_weight DECIMAL(12,3) NOT NULL,
    net_weight DECIMAL(12,3) NOT NULL,
    weighment_date DATETIME NOT NULL,
    operator_id BIGINT,
    scale_id VARCHAR(50),
    first_weight_at DATETIME,
    second_weight_at DATETIME,
    variance_kg DECIMAL(10,3),
    notes VARCHAR(500),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_by VARCHAR(50) DEFAULT 'system',
    updated_by VARCHAR(50),
    FOREIGN KEY (gate_entry_id) REFERENCES gate_entries(id),
    FOREIGN KEY (warehouse_id) REFERENCES warehouses(id),
    FOREIGN KEY (vehicle_id) REFERENCES vehicles(id),
    FOREIGN KEY (trip_id) REFERENCES trips(id),
    FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders(id),
    FOREIGN KEY (operator_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE quality_parameters (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    product_id BIGINT NOT NULL,
    parameter_name VARCHAR(100) NOT NULL,
    parameter_unit VARCHAR(20),
    min_value DECIMAL(10,3),
    max_value DECIMAL(10,3),
    target_value DECIMAL(10,3),
    is_mandatory BOOLEAN NOT NULL DEFAULT TRUE,
    deduction_rate DECIMAL(8,4),
    rejection_threshold DECIMAL(10,3),
    display_order INT DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_by VARCHAR(50) DEFAULT 'system',
    updated_by VARCHAR(50),
    FOREIGN KEY (product_id) REFERENCES products(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE quality_inspections (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    inspection_number VARCHAR(30) NOT NULL UNIQUE,
    weighment_id BIGINT,
    purchase_order_id BIGINT,
    warehouse_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    grade_id BIGINT,
    inspector_id BIGINT,
    inspection_date DATETIME NOT NULL,
    overall_result ENUM('PASS','WARNING','DEDUCTION','REJECT') NOT NULL DEFAULT 'PASS',
    total_deduction_percent DECIMAL(8,4) DEFAULT 0,
    total_deduction_amount DECIMAL(12,2) DEFAULT 0,
    final_grade_id BIGINT,
    notes TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_by VARCHAR(50) DEFAULT 'system',
    updated_by VARCHAR(50),
    FOREIGN KEY (weighment_id) REFERENCES weighments(id),
    FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders(id),
    FOREIGN KEY (warehouse_id) REFERENCES warehouses(id),
    FOREIGN KEY (product_id) REFERENCES products(id),
    FOREIGN KEY (inspector_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE quality_inspection_results (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    inspection_id BIGINT NOT NULL,
    parameter_id BIGINT NOT NULL,
    measured_value DECIMAL(10,3),
    result ENUM('PASS','WARNING','DEDUCTION','REJECT') NOT NULL,
    deduction_percent DECIMAL(8,4) DEFAULT 0,
    notes VARCHAR(500),
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (inspection_id) REFERENCES quality_inspections(id),
    FOREIGN KEY (parameter_id) REFERENCES quality_parameters(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE warehouse_receipts (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    receipt_number VARCHAR(30) NOT NULL UNIQUE,
    warehouse_id BIGINT NOT NULL,
    purchase_order_id BIGINT,
    trip_id BIGINT,
    gate_entry_id BIGINT,
    weighment_id BIGINT,
    inspection_id BIGINT,
    product_id BIGINT NOT NULL,
    grade_id BIGINT,
    received_quantity DECIMAL(12,3) NOT NULL,
    accepted_quantity DECIMAL(12,3) NOT NULL,
    rejected_quantity DECIMAL(12,3) DEFAULT 0,
    deduction_quantity DECIMAL(12,3) DEFAULT 0,
    net_quantity DECIMAL(12,3) NOT NULL,
    receipt_date DATETIME NOT NULL,
    received_by BIGINT,
    status ENUM('DRAFT','COMPLETED','CANCELLED') NOT NULL DEFAULT 'DRAFT',
    notes TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_by VARCHAR(50) DEFAULT 'system',
    updated_by VARCHAR(50),
    FOREIGN KEY (warehouse_id) REFERENCES warehouses(id),
    FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders(id),
    FOREIGN KEY (trip_id) REFERENCES trips(id),
    FOREIGN KEY (gate_entry_id) REFERENCES gate_entries(id),
    FOREIGN KEY (weighment_id) REFERENCES weighments(id),
    FOREIGN KEY (inspection_id) REFERENCES quality_inspections(id),
    FOREIGN KEY (product_id) REFERENCES products(id),
    FOREIGN KEY (received_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
